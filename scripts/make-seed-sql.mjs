// Builds supabase/seed.sql from data/directory.json.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync } from 'node:fs'

const data = JSON.parse(readFileSync(new URL('../data/directory.json', import.meta.url)))
const q = (v) => (v === null || v === undefined || v === '' ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)

const pCols = ['id', 'program', 'level', 'state', 'funds_what', 'hub_stage', 'award_range', 'match_requirement', 'cycle_deadline', 'eligibility_notes', 'url', 'date_verified', 'none_found']
const sCols = ['state', 'status', 'programs_found', 'categories_none', 'categories_unchecked', 'largest_award', 'rank', 'why']

let sql = '-- Generated by scripts/make-seed-sql.mjs. Replaces all rows.\nbegin;\ntruncate public.programs, public.states;\n'
sql += `insert into public.programs (${pCols.join(', ')}) values\n` + data.programs.map((p) => `(${pCols.map((c) => q(p[c])).join(', ')})`).join(',\n') + ';\n'
sql += `insert into public.states (${sCols.join(', ')}) values\n` + data.states.map((s) => `(${sCols.map((c) => q(s[c])).join(', ')})`).join(',\n') + ';\n'
sql += 'commit;\n'
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote supabase/seed.sql: ${data.programs.length} programs, ${data.states.length} states`)
